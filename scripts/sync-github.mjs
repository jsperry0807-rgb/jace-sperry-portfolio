/**
 * Refreshes the GitHub contribution snapshot used by the portfolio.
 *
 *   pnpm sync:github
 *
 * GitHub only exposes the contribution calendar over GraphQL, so this data is
 * generated locally and committed. The public repo stats and language mix are
 * fetched live at build time; this file only covers the heatmap and commit
 * totals.
 *
 * Requires an authenticated `gh` CLI, or a `GITHUB_TOKEN` with `read:user`
 * access. If GitHub is unavailable, the committed snapshot is kept and the
 * command exits 0 unless `--strict` is passed.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const login = process.env.GITHUB_USERNAME?.trim() || "jsperry0807-rgb";

function token() {
  if (process.env.GITHUB_TOKEN?.trim()) return process.env.GITHUB_TOKEN.trim();

  try {
    return execFileSync("gh", ["auth", "token"], { encoding: "utf8" }).trim();
  } catch {
    throw new Error(
      "No GitHub token found. Run `gh auth login`, or set GITHUB_TOKEN.",
    );
  }
}

const CONTRIBUTION_QUERY = `query ($login: String!) {
  user(login: $login) {
    contributionsCollection {
      totalCommitContributions
      totalPullRequestContributions
      totalIssueContributions
      totalPullRequestReviewContributions
      totalRepositoriesWithContributedCommits
      restrictedContributionsCount
      commitContributionsByRepository(maxRepositories: 100) {
        repository { nameWithOwner }
        contributions { totalCount }
      }
      contributionCalendar {
        totalContributions
        weeks {
          firstDay
          contributionDays { date contributionCount weekday }
        }
      }
    }
  }
}`;

try {
const response = await fetch("https://api.github.com/graphql", {
  method: "POST",
  headers: {
    Authorization: `Bearer ${token()}`,
    "Content-Type": "application/json",
    "User-Agent": "jace-sperry-portfolio",
  },
  body: JSON.stringify({
    query: CONTRIBUTION_QUERY,
    variables: { login },
  }),
});

if (!response.ok) {
  throw new Error(`${response.status} ${response.statusText} from GitHub GraphQL`);
}

const payload = await response.json();

if (payload.errors?.length) {
  throw new Error(payload.errors.map((error) => error.message).join("; "));
}

const collection = payload.data?.user?.contributionsCollection;
if (!collection?.contributionCalendar) {
  throw new Error("No contribution data returned for this account.");
}

const weeks = collection.contributionCalendar.weeks.map((week) => ({
  firstDay: week.firstDay,
  days: week.contributionDays.map((day) => ({
    date: day.date,
    count: day.contributionCount,
    weekday: day.weekday,
  })),
}));

const days = weeks.flatMap((week) => week.days);

let longestStreak = 0;
let run = 0;
for (const day of days) {
  run = day.count > 0 ? run + 1 : 0;
  longestStreak = Math.max(longestStreak, run);
}

const activeDays = days.filter((day) => day.count > 0).length;

const snapshot = {
  fetchedAt: new Date().toISOString(),
  login,
  contributions: collection.contributionCalendar.totalContributions,
  commits: collection.totalCommitContributions,
  pullRequests: collection.totalPullRequestContributions,
  issues: collection.totalIssueContributions,
  reviews: collection.totalPullRequestReviewContributions,
  privateContributions: collection.restrictedContributionsCount,
  repositories: collection.totalRepositoriesWithContributedCommits,
  activeDays,
  totalDays: days.length,
  longestStreak,
  activePercent: days.length > 0 ? (activeDays / days.length) * 100 : 0,
  windowStart: days[0]?.date ?? "",
  windowEnd: days.at(-1)?.date ?? "",
  weeks,
  byRepository: collection.commitContributionsByRepository
    .map((entry) => ({
      name: entry.repository.nameWithOwner,
      commits: entry.contributions.totalCount,
    }))
    .filter((entry) => entry.commits > 0)
    .sort((a, b) => b.commits - a.commits),
};

const header = `// Generated by scripts/sync-github.mjs — do not edit by hand.
// Refresh it with: pnpm sync:github

export type ContributionDay = {
  date: string;
  count: number;
  weekday: number;
};

export type ContributionWeek = {
  firstDay: string;
  days: ContributionDay[];
};

export type ContributionRepo = {
  name: string;
  commits: number;
};

export type ContributionSnapshot = {
  fetchedAt: string;
  login: string;
  contributions: number;
  commits: number;
  pullRequests: number;
  issues: number;
  reviews: number;
  privateContributions: number;
  repositories: number;
  activeDays: number;
  totalDays: number;
  longestStreak: number;
  activePercent: number;
  windowStart: string;
  windowEnd: string;
  weeks: ContributionWeek[];
  byRepository: ContributionRepo[];
};

export const contributionSnapshot: ContributionSnapshot = `;

const output = `${header}${JSON.stringify(snapshot, null, 2)};\n`;
const target = fileURLToPath(new URL("../lib/github-contributions.ts", import.meta.url));

writeFileSync(target, output);

console.log(
  `Wrote ${target}\n${snapshot.contributions} contributions · ${snapshot.activeDays} active days · ${snapshot.byRepository.length} repos`,
);
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);

  if (process.argv.includes("--strict")) {
    console.error(`GitHub sync failed: ${message}`);
    process.exit(1);
  }

  console.warn(
    `GitHub sync skipped: ${message}\nKeeping the committed snapshot in lib/github-contributions.ts.`,
  );
  process.exit(0);
}
